<#
.SYNOPSIS
    Checks that every relative link and image in the repository's markdown points at something.

.DESCRIPTION
    markdownlint checks how a document is written and says nothing about whether what it points at
    is there. That is the failure worth catching here, because it is invisible in the source and
    obvious to a reader: a broken image on a published page, or a link into a file somebody renamed.

    **The images are checked in both directions.** A picture nothing refers to is as much a defect
    as a reference to a picture that is not there: the screenshots are generated by a test fixture,
    so an orphan means either a page that forgot one or a fixture still taking one nobody wants.

    Anchors are not followed. A link to a heading that has since been renamed is a real defect and
    a different one, and resolving it means parsing every document's headings, which is a markdown
    implementation this does not need to grow.

.PARAMETER Root
    The repository root. Everything is reported relative to it.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string] $Root
)

$ErrorActionPreference = 'Stop'

# **The documents this repository has, which is what git tracks.** A list of directories to skip
# is a list that has to be added to, and the thing it forgets is always something a tool created:
# `node_modules` was named, `.venv` was not, and a checker walking somebody's vendored dependencies
# reports on files nobody here wrote and fails on a `[LICENSE](LICENSE)` inside one of them.
# `.gitignore` already says what is not ours, and it is maintained for its own reasons.
#
# Asked under `Continue` and judged by the exit code alone, as `Anchors.ps1` asks git everything.
# Under `Stop` a line git writes to stderr ends this script the moment anything upstream merges
# the streams, which is what capturing the gate's output does, and git writes warnings on commands
# that succeed.
$quietly = $ErrorActionPreference
Push-Location $Root
try {
    $ErrorActionPreference = 'Continue'
    $tracked = @(& git ls-files -- '*.md')
    $listed = ($LASTEXITCODE -eq 0)
}
finally {
    $ErrorActionPreference = $quietly
    Pop-Location
}

if (-not $listed) { throw 'git could not list the markdown files.' }

$documents = $tracked | ForEach-Object { Get-Item -LiteralPath (Join-Path $Root $_) }

$broken = @()
$referenced = @{}

# `[text](target)` and `![text](target)`, which is every link this repository writes. Reference
# style definitions are not used anywhere here, and a checker that pretended to understand them
# without being tested against one would be worse than one that says it does not.
$pattern = '!?\[[^\]]*\]\(([^)]+)\)'

foreach ($document in $documents) {
    # **The whole document, not a line at a time.** This repository wraps its prose near a hundred
    # characters, so a link may be wrapped, and a checker reading one line never sees one that
    # broke across two. It found nothing and said so, which is the worst of the three answers.
    $text = Get-Content -LiteralPath $document.FullName -Raw

    # **With LF endings.** A Windows checkout is CRLF, and in a multiline pattern `$` matches only
    # before `\n`, so with the `\r` left in, no closing fence would ever match and no fenced block
    # would be taken out.
    $text = $text -replace "`r`n", "`n"

    # **And not what it is showing rather than saying.** A page explaining how to add a picture
    # writes the markdown for one in a fenced block, and a checker that cannot tell the two apart
    # fails the gate over an example. The block goes first, because an odd number of backticks
    # inside one would otherwise pair with the next in the prose after it and hide what lies
    # between. Each is replaced by the line breaks it held, so a link after it is still reported
    # at its own line.
    $blank = { param($found) "`n" * [regex]::Matches($found.Value, "`n").Count }
    $text = [regex]::Replace($text, '(?ms)^(```|~~~).*?^\1[^\r\n]*$', $blank)
    $text = [regex]::Replace($text, '`[^`]*`', $blank)

    foreach ($match in [regex]::Matches($text, $pattern)) {
        $target = ($match.Groups[1].Value -replace '\s+', ' ').Trim()

        # Somewhere else entirely, or a link to a heading in this document.
        if ($target -match '^[a-z][a-z0-9+.-]*:' -or $target.StartsWith('#')) {
            continue
        }

        # What CommonMark allows around a destination and is not part of it: angle brackets, and a
        # title after it in quotes or parentheses.
        if ($target -match '^<(.*?)>\s*(.*)$') {
            $target = $Matches[1]
        }
        else {
            $target = ($target -replace '\s+(".*"|''.*''|\(.*\))$', '')
        }

        $path = ($target -split '[#?]')[0]
        if (-not $path) { continue }

        $number = ($text.Substring(0, $match.Index) -split "`n").Count
        $where = $document.FullName.Substring($Root.Length).TrimStart('\', '/')

        # **Answered rather than thrown.** `GetFullPath` raises `ArgumentException` on a character
        # that cannot be in a path, and with `Stop` in force that ends the run: no document name,
        # no line, and every genuinely broken link in the repository left unreported behind it.
        if ($path.IndexOfAny([IO.Path]::GetInvalidPathChars()) -ge 0) {
            $broken += "$where line ${number}: $target is not a usable path"
            continue
        }

        $full = [IO.Path]::GetFullPath((Join-Path $document.DirectoryName $path))

        if (Test-Path -LiteralPath $full) {
            $referenced[$full.ToLowerInvariant()] = $true
        }
        else {
            $broken += "$where line ${number}: $target"
        }
    }
}

$images = Join-Path $Root 'docs\images'
if (Test-Path $images) {
    foreach ($image in Get-ChildItem -Path $images -File) {
        if (-not $referenced.ContainsKey($image.FullName.ToLowerInvariant())) {
            $broken += "docs\images\$($image.Name): no page refers to it"
        }
    }
}

if ($broken.Count -gt 0) {
    foreach ($problem in $broken) {
        Write-Host "  $problem" -ForegroundColor Red
    }

    throw "$($broken.Count) markdown link(s) point at nothing."
}

Write-Host "  $($documents.Count) documents, every link and image resolves."
